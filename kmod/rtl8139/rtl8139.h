#pragma once

#include <stdint.h>

#define RTL8139_VENDOR_ID 0x10ec
#define RTL8139_DEVICE_ID 0x8139
#define RTL8139_MTU 1500
#define RTL8139_MAX_FRAME_SIZE 1536
#define RTL8139_MIN_FRAME_SIZE 60
#define RTL8139_RX_RING_SIZE 32768
#define RTL8139_RX_ALLOC_SIZE (RTL8139_RX_RING_SIZE + 16 + 2048)
#define RTL8139_TX_DESC_COUNT 4
#define RTL8139_TX_BUFFER_SIZE 1792

#define RTL8139_REG_MAC0       0x00
#define RTL8139_REG_MAR0       0x08
#define RTL8139_REG_TX_STATUS0 0x10
#define RTL8139_REG_TX_ADDR0   0x20
#define RTL8139_REG_RX_BUF     0x30
#define RTL8139_REG_CHIP_CMD   0x37
#define RTL8139_REG_RX_BUF_PTR 0x38
#define RTL8139_REG_RX_BUF_ADDR 0x3a
#define RTL8139_REG_INTR_MASK  0x3c
#define RTL8139_REG_INTR_STATUS 0x3e
#define RTL8139_REG_TX_CONFIG  0x40
#define RTL8139_REG_RX_CONFIG  0x44
#define RTL8139_REG_CFG9346    0x50
#define RTL8139_REG_CONFIG1    0x52

#define RTL8139_CMD_RESET 0x10
#define RTL8139_CMD_RX_ENABLE 0x08
#define RTL8139_CMD_TX_ENABLE 0x04
#define RTL8139_CMD_RX_EMPTY 0x01

#define RTL8139_RX_CONFIG_RING_32K (2U << 11)
#define RTL8139_RX_CONFIG_WRAP 0x80
#define RTL8139_RX_CONFIG_ACCEPT_ERR 0x20
#define RTL8139_RX_CONFIG_ACCEPT_RUNT 0x10
#define RTL8139_RX_CONFIG_ACCEPT_BROADCAST 0x08
#define RTL8139_RX_CONFIG_ACCEPT_MULTICAST 0x04
#define RTL8139_RX_CONFIG_ACCEPT_PHYSICAL 0x02
#define RTL8139_RX_CONFIG_ACCEPT_ALL 0x01

#define RTL8139_TX_STATUS_OK 0x8000
#define RTL8139_TX_STATUS_HOST_OWNS 0x2000
#define RTL8139_TX_STATUS_ABORTED 0x40000000U
#define RTL8139_TX_STATUS_CARRIER_LOST 0x80000000U
#define RTL8139_TX_FIFO_THRESHOLD (8U << 16)

#define RTL8139_RX_STATUS_OK 0x0001
#define RTL8139_RX_STATUS_BAD_SYMBOL 0x0020
#define RTL8139_RX_STATUS_RUNT 0x0010
#define RTL8139_RX_STATUS_TOO_LONG 0x0008
#define RTL8139_RX_STATUS_CRC 0x0004
#define RTL8139_RX_STATUS_ALIGN 0x0002

#define RTL8139_RX_RING_MASK (RTL8139_RX_RING_SIZE - 1)

typedef struct rtl8139_device {
    uint16_t io_base;
    uint8_t mac[6];
    uint8_t *rx_ring;
    uint64_t rx_ring_phys;
    uint32_t rx_offset;
    uint8_t rx_lock;
    uint8_t tx_lock;
    uint8_t *tx_buffers[RTL8139_TX_DESC_COUNT];
    uint64_t tx_phys[RTL8139_TX_DESC_COUNT];
    uint8_t tx_index;
    bool tx_pending[RTL8139_TX_DESC_COUNT];
} rtl8139_device_t;
